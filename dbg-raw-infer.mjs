import net from "node:net";
import { Tokenizer } from "@huggingface/tokenizers";
import fs from "node:fs";
const tok = new Tokenizer(JSON.parse(fs.readFileSync("laya-multilingual-int8/tokenizer/tokenizer.json", "utf8")), JSON.parse(fs.readFileSync("laya-multilingual-int8/tokenizer/tokenizer_config.json", "utf8")));
const id = (t) => tok.token_to_id(t);
const n = 1, L = 512, K = 3;
const seq = new Int32Array(L).fill(id("<pad>"));
seq[0] = id("<s>"); 
const att = new BigInt64Array(n*L).fill(1n); att[L-1] = 0n;
const mpos = new BigInt64Array(n*K); for (let j = 0; j < K; j++) mpos[j] = BigInt(100+j*10);
const mmsk = new Uint8Array(n*K).fill(1);
const qt = new BigInt64Array(n); qt[0] = 0n;
const hdr = Buffer.alloc(20);
hdr.writeUInt32LE(0x4c415941, 0); hdr.writeUInt8(0, 4);
hdr.writeUInt32LE(n, 8); hdr.writeUInt32LE(L, 12); hdr.writeUInt32LE(K, 16);
const body = Buffer.concat([hdr, ...[seq, new BigInt64Array(n*L).fill(1n), mpos, mmsk, qt].map(a => Buffer.from(a.buffer, a.byteOffset, a.byteLength))]);
const frame = Buffer.alloc(4); frame.writeUInt32LE(body.length, 0);
const sock = net.createConnection(new URL("./laya-multi.sock", import.meta.url).pathname);
sock.on("connect", () => { console.log("connected, sending", body.length + 4, "bytes"); sock.write(Buffer.concat([frame, body])); });
let got = 0;
sock.on("data", (d) => { got += d.length; console.log("data:", d.length, "total:", got); if (got >= 40) { console.log("hex head:", d.subarray(0, Math.min(24, d.length)).toString("hex")); process.exit(0); } });
sock.on("error", (e) => console.log("err", e.code));
setTimeout(() => { console.log("TIMEOUT got", got); process.exit(1); }, 15000);
