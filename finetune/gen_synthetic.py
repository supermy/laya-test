def gen_risk(n_target):
    g = Gen(400)
    rng = random.Random(303)

    def formal(t):
        """风控文本用正式前后缀变化(不加口语词)"""
        p = rng.random()
        if p < 0.3:
            return rng.choice(RISK_PRE) + t
        if p < 0.6:
            return t + rng.choice(RISK_SUF)
        if p < 0.7:
            return t  # 留 30% 无修饰
        return rng.choice(RISK_PRE) + t + rng.choice(RISK_SUF)

    def m_clean():
        return g.add(formal(fill(rng, rng.choice(RISK_CLEAN))), risk_type="无风险信号", risk_level=1, review=0)

    def m_credit():
        return g.add(formal(fill(rng, rng.choice(RISK_CREDIT))), risk_type="信用风险",
                     risk_level=rng.choice([2, 2, 3]), review=1 if rng.random() < 0.1 else 0)

    def m_fraud():
        return g.add(formal(fill(rng, rng.choice(RISK_FRAUD))), risk_type="欺诈风险",
                     risk_level=rng.choice([4, 5, 5]), review=1)

    def m_comply():
        lvl = rng.choice([3, 4])
        return g.add(formal(fill(rng, rng.choice(RISK_COMPLY))), risk_type="合规风险",
                     risk_level=lvl, review=1 if lvl >= 4 else 0)

    n = n_target // 4
    g.quota(int(n * 2.2), m_clean)
    g.quota(n, m_credit)
    g.quota(n, m_fraud)
    g.quota(int(n * 0.6), m_comply)
    return g.rows


