def gen_agent(n_target):
    g = Gen(400)
    rng = random.Random(202)

    def make(pool, label, lo, hi, n, ms_always=False, ms_prob=0.0):
        def m():
            return g.add(vary(rng, fill(rng, rng.choice(pool))), label=label,
                         complexity=rng.randint(lo, hi),
                         multi_step=1 if (ms_always or rng.random() < ms_prob) else 0)
        g.quota(n, m)

    per = n_target // 5
    make(AGENT_DIRECT, "直接回答", 1, 2, per)
    make(AGENT_RETRIEVE, "检索问答", 2, 3, per, ms_prob=0.05)
