def split_and_write(prefix, rows, label_key, classes, normal_label,
                    test_ratio=0.05, min_test_per_class=100, seed=42):
    """按类别分层切分并写 train/test/classes.json(convert_stock.py 同款格式)"""
    cnt = Counter(r[label_key] for r in rows)
    rng = random.Random(seed)
    train, test = [], []
    for lab in classes:
        pool = [r for r in rows if r[label_key] == lab]
        rng.shuffle(pool)
        k = min(len(pool), max(min_test_per_class, int(len(pool) * test_ratio)))
        test += pool[:k]
        train += pool[k:]
    rng.shuffle(train)
    rng.shuffle(test)
    with open(f"{DATA}/{prefix}-train.jsonl", "w", encoding="utf-8") as f:
        for d in train:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    with open(f"{DATA}/{prefix}-test.jsonl", "w", encoding="utf-8") as f:
        for d in test:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    with open(f"{DATA}/{prefix}-classes.json", "w", encoding="utf-8") as f:
        json.dump({"classes": classes, "normal_label": normal_label,
                   "counts": {l: cnt[l] for l in classes}}, f, ensure_ascii=False, indent=2)
    print(f"[{prefix}] 原始 {len(rows)} train={len(train)} test={len(test)}")
    print(f"[{prefix}] 分布: {dict(cnt)}")


def fill(rng, entry):
    """entry = (template, [slot values...], ...) -> 随机填充后的字符串"""
    t = entry[0]
    args = [rng.choice(sub) if isinstance(sub, list) else sub for sub in entry[1:]]
    return t.format(*args)


PRE = ["说实话，", "讲真，", "问一下，", "求助：", "更新一下：", "补充一句，", "刚看到，", "第一次发帖，", "老用户了，", "路过评论，"]
SUF = ["！", "。", "哈", "呀", "~", "，谢谢", "，在线等", "，蹲回复", "……", "，大家觉得呢"]


def vary(rng, t):
    """加前后缀变化,把模板组合数放大 ~100 倍"""
    p = rng.random()
    if p < 0.35:
        return rng.choice(PRE) + t
    if p < 0.7:
        return t + rng.choice(SUF)
    return rng.choice(PRE) + t + rng.choice(SUF)


class Gen:
    """带去重和死循环保护的累加器"""
    def __init__(self, maxlen):
        self.rows, self.seen = [], set()
        self.maxlen = maxlen

    def add(self, text, **fields):
        text = re.sub(r"\s+", " ", text).strip()
        if not text or text in self.seen:
            return False
        self.seen.add(text)
        fields["text"] = text[: self.maxlen]
        self.rows.append(fields)
        return True

    def quota(self, n, fn):
        made, attempts = 0, 0
        while made < n:
            attempts += 1
            if attempts > n * 60:
                raise RuntimeError(f"模板组合耗尽: {fn.__name__} 只凑到 {made}/{n},请加模板或降低 --n")
            if fn():
                made += 1
        return made


