def gen_ugc(n_target):
    g = Gen(500)
    rng = random.Random(101)
    n0, n1, n2, n3 = int(n_target * 0.28), int(n_target * 0.24), int(n_target * 0.18), int(n_target * 0.10)
    n4 = n_target - n0 - n1 - n2 - n3

    def m0():
        if rng.random() < 0.12:
            return g.add(rng.choice(UGC_HARD_NEG), label="正常", severity=1, review=1)
        return g.add(vary(rng, fill(rng, rng.choice(UGC_GOOD))), label="正常",
                     severity=1, review=1 if rng.random() < 0.05 else 0)

    def m1():
        if rng.random() < 0.65:
            return g.add(vary(rng, fill(rng, rng.choice(UGC_AD))), label="广告导流",
                         severity=rng.choice([2, 3]), review=0)
        return g.add(vary(rng, fill(rng, rng.choice(UGC_AD_SOFT))), label="广告导流",
                     severity=2, review=1)

    def m2():
        return g.add(vary(rng, fill(rng, (rng.choice(UGC_INSULT), *rng.choice(UGC_INSULT_WORDS)))),
                     label="辱骂攻击", severity=rng.choice([3, 3, 4]),
                     review=1 if rng.random() < 0.1 else 0)

    def m3():
        return g.add(vary(rng, fill(rng, rng.choice(UGC_PORN))), label="色情低俗",
                     severity=rng.choice([4, 5]), review=0)

    def m4():
        return g.add(vary(rng, fill(rng, rng.choice(UGC_SCAM))), label="诈骗引流",
                     severity=rng.choice([4, 5, 5]), review=1 if rng.random() < 0.06 else 0)

    g.quota(n0, m0), g.quota(n1, m1), g.quota(n2, m2), g.quota(n3, m3), g.quota(n4, m4)
    return g.rows


